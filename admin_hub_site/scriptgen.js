function csvToArr(s){return s.split(",").map(function(x){return x.trim()}).filter(Boolean)}
function buildCA(){
  var name=$("ca-name").value.trim()||"New Conditional Access policy";
  var users=csvToArr($("ca-users").value);
  var exclude=csvToArr($("ca-exclude").value);
  var apps=csvToArr($("ca-apps").value);
  var state=$("ca-state").value;
  var grants=[];
  if($("ca-mfa").checked)grants.push('"mfa"');
  if($("ca-compliant").checked)grants.push('"compliantDevice"');
  var lines=["# Conditional Access policy: "+name,
    "# Generated by admin_hub — always create new policies in report-only mode first.",
    "Connect-MgGraph -Scopes \"Policy.ReadWrite.ConditionalAccess\"",
    "",
    "$params = @{",
    "    DisplayName = "+psStr(name),
    "    State       = "+psStr(state),
    "    Conditions  = @{",
    "        Users = @{",
    "            IncludeUsers = @("+(users.length?users.map(psStr).join(", "):'"All"')+")",
    "            ExcludeUsers = @("+(exclude.length?exclude.map(psStr).join(", "):"")+")",
    "        }",
    "        Applications = @{",
    "            IncludeApplications = @("+(apps.length?apps.map(psStr).join(", "):'"All"')+")",
    "        }"];
  if($("ca-legacy").checked)
    lines.push("        ClientAppTypes = @(\"exchangeActiveSync\", \"other\")");
  lines.push("    }");
  if(grants.length){
    lines.push("    GrantControls = @{",
      "        Operator        = \"OR\"",
      "        BuiltInControls = @("+grants.join(", ")+")",
      "    }");
  }
  lines.push("}","","New-MgIdentityConditionalAccessPolicy -BodyParameter $params");
  return lines.join("\n");
}
$("ca-go").addEventListener("click",function(){$("ca-out").textContent=buildCA()});

