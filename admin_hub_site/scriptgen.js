function psStr(s){return "'"+String(s||"").replace(/'/g,"''")+"'"}

// ---- offboarding ----
function buildOffboard(){
  var upn=$("ob-upn").value.trim()||"user@contoso.com";
  var lines=["# Offboarding script for "+upn,
             "# Generated by admin_hub — review before running.",
             "Connect-MgGraph -Scopes \"User.ReadWrite.All\",\"Directory.ReadWrite.All\",\"Group.ReadWrite.All\"",
             "",
             "$upn = "+psStr(upn),
             "$user = Get-MgUser -UserId $upn"];
  if($("ob-block").checked)lines.push("","# Block sign-in","Update-MgUser -UserId $user.Id -AccountEnabled:$false");
  if($("ob-revoke").checked)lines.push("","# Revoke all refresh tokens and sessions","Revoke-MgUserSignInSession -UserId $user.Id");
  if($("ob-lic").checked)lines.push("","# Remove all assigned licenses","$skus = (Get-MgUserLicenseDetail -UserId $user.Id).SkuId","Set-MgUserLicense -UserId $user.Id -AddLicenses @() -RemoveLicenses $skus");
  if($("ob-groups").checked)lines.push("","# Remove from all Entra ID group memberships","Get-MgUserMemberOf -UserId $user.Id | ForEach-Object {","    Remove-MgGroupMemberByRef -GroupId $_.Id -DirectoryObjectId $user.Id -ErrorAction SilentlyContinue","}");
  if($("ob-gal").checked)lines.push("","# Hide from the global address list (requires Exchange Online module)","# Connect-ExchangeOnline","Set-Mailbox -Identity $upn -HiddenFromAddressListsEnabled $true");
  if($("ob-mailbox").checked)lines.push("","# Convert mailbox to shared (requires Exchange Online module)","# Connect-ExchangeOnline","Set-Mailbox -Identity $upn -Type Shared");
  if($("ob-manager").checked){
    var fwd=$("ob-fwd").value.trim()||"manager@contoso.com";
    lines.push("","# Forward mail to "+fwd+" (requires Exchange Online module)","# Connect-ExchangeOnline","Set-Mailbox -Identity $upn -ForwardingAddress "+psStr(fwd)+" -DeliverToMailboxAndForward $false");
  }
  lines.push("","Write-Host \"Offboarding steps complete for $upn\" -ForegroundColor Green");
  return lines.join("\n");
}
$("ob-go").addEventListener("click",function(){$("ob-out").textContent=buildOffboard()});

// ---- bulk user creation ----
function buildBulk(){
  var raw=$("bk-in").value.trim();
  var loc=($("bk-loc").value.trim()||"DE").toUpperCase();
  if(!raw)return "# Paste at least one line: Display Name,UPN,Password";
  var rows=raw.split("\n").map(function(l){return l.trim()}).filter(Boolean);
  var lines=["# Bulk user creation script",
             "# Generated by admin_hub — review before running.",
             "Connect-MgGraph -Scopes \"User.ReadWrite.All\"",
             "",
             "$users = @("];
  rows.forEach(function(r,i){
    var parts=r.split(",").map(function(x){return x.trim()});
    var name=parts[0]||"User "+(i+1), upn=parts[1]||("user"+(i+1)+"@contoso.com"), pw=parts[2]||"ChangeMe-"+(i+1)+"!";
    lines.push("    @{ DisplayName = "+psStr(name)+"; Upn = "+psStr(upn)+"; Password = "+psStr(pw)+" }"+(i<rows.length-1?"":""));
  });
  lines.push(")","",
    "foreach ($u in $users) {",
    "    $passwordProfile = @{",
    "        Password = $u.Password",
    "        ForceChangePasswordNextSignIn = $true",
    "    }",
    "    $mailNickname = ($u.Upn -split \"@\")[0]",
    "    New-MgUser -DisplayName $u.DisplayName -UserPrincipalName $u.Upn -AccountEnabled `",
    "        -MailNickname $mailNickname -PasswordProfile $passwordProfile -UsageLocation "+psStr(loc),
    "    Write-Host \"Created $($u.Upn)\" -ForegroundColor Green",
    "}");
  return lines.join("\n");
}
$("bk-go").addEventListener("click",function(){$("bk-out").textContent=buildBulk()});

// ---- mailbox permissions ----
function buildMailbox(){
  var target=$("mb-target").value.trim()||"team-shared@contoso.com";
  var grantee=$("mb-grantee").value.trim()||"jane.doe@contoso.com";
  var lines=["# Mailbox permission grant","# Generated by admin_hub — review before running.","Connect-ExchangeOnline","",
             "$target  = "+psStr(target),"$grantee = "+psStr(grantee)];
  if($("mb-full").checked){
    var auto=$("mb-auto").checked;
    lines.push("","# Full Access"+(auto?" (auto-mapped in Outlook)":" (not auto-mapped)"),
      "Add-MailboxPermission -Identity $target -User $grantee -AccessRights FullAccess -InheritanceType All"+(auto?"":" -AutoMapping $false"));
  }
  if($("mb-sendas").checked)lines.push("","# Send As","Add-RecipientPermission -Identity $target -Trustee $grantee -AccessRights SendAs -Confirm:$false");
  if($("mb-sob").checked)lines.push("","# Send on Behalf","Set-Mailbox -Identity $target -GrantSendOnBehalfTo @{Add=$grantee}");
  lines.push("","Write-Host \"Permissions granted on $target for $grantee\" -ForegroundColor Green");
  return lines.join("\n");
}
$("mb-go").addEventListener("click",function(){$("mb-out").textContent=buildMailbox()});

